    ("gate", "`openreadout analyze gate FILE.fcs --workspace W.wsp --json` (or `--gatingml G.xml`)"),
    ("batch-table", "`openreadout batch MEASURE INPUTS… --json` and `openreadout stats|trace|table|info FILES… --tidy --json` (also `analyze gate`)"),
