    ("chromatogram", "`openreadout analyze chromatogram FILE --json` (`--tic`, `--bpc`, `--mz M`, `--transition Q1>Q3`, `--trace N`)"),
    ("peaks", "`openreadout analyze peaks FILE --json` (`--rt T --window W`, `--integrate A-B`, `--targets LIST.csv`)"),
    ("assay", "`openreadout analyze assay wells|curve|dose-response|kinetics|growth|qc FILE --json`"),
    ("qpcr", "`openreadout analyze qpcr FILE --json` (`--cq`, `--ddcq`, `--standard-curve`)"),
