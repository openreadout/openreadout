    ("info-structure", "`openreadout info FILE --view structure --json`"),
    ("check", "`openreadout check FILE --json`"),
    ("check-planes", "`openreadout check FILE --planes --json`"),
    ("check-against", "`openreadout check A --against B --json` (also the MCP tool `openreadout_check` with `against`)"),
    ("check-report", "`openreadout check FILE --report --json` (the bundle itself is `report`; also the MCP tool `openreadout_check` with `report: true`)"),
    ("export", "`openreadout export FILE --json`"),
    ("export-attachment", "`openreadout export FILE --attachment NAME --json`"),
    ("spectra", "`openreadout spectra FILE --json` (`--ms-level`, `--polarity`, `--rt A-B`, `--precursor MZ`, `--charge`, `--count`)"),
    ("spectrum", "`openreadout spectra FILE --scan N --json` (or `--index I`, `--ms-level L --nth K`)"),
