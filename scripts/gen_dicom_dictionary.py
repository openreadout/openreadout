#!/usr/bin/env python3
"""Write the DICOM data dictionary used by `openreadout-medical` from the published standard.

Usage: python3 scripts/gen_dicom_dictionary.py part06.xml > crates/openreadout-medical/src/dicom/dictionary_table.rs

`part06.xml` is DICOM PS3.6 (Data Dictionary) in DocBook form, published by NEMA at
https://dicom.nema.org/medical/dicom/current/source/docbook/part06/part06.xml. Only table 6-1
(registry of data elements) and 7-1 (file meta elements) are read: tag, keyword and VR. Tags
with `x` digits (repeating groups such as overlays, `60xx`) become a mask and a value.
"""
import re
import sys
import xml.etree.ElementTree as ET

NS = {"d": "http://docbook.org/ns/docbook"}


def text(el) -> str:
    s = "".join(el.itertext())
    return re.sub(r"\s+", " ", s.replace("​", "")).strip()


def rows(root, table_id):
    for t in root.iter("{http://docbook.org/ns/docbook}table"):
        if t.get("{http://www.w3.org/XML/1998/namespace}id") == table_id:
            for tr in t.find("d:tbody", NS).findall("d:tr", NS):
                yield [text(td) for td in tr.findall("d:td", NS)]


def main() -> None:
    root = ET.parse(sys.argv[1]).getroot()
    edition = ""
    sub = root.find(".//d:subtitle", NS)
    if sub is not None:
        edition = text(sub)
    out = {}
    for table in ("table_6-1", "table_7-1", "table_8-1"):
        for cells in rows(root, table):
            if len(cells) < 4:
                continue
            tag, keyword, vr = cells[0], cells[2], cells[3]
            m = re.fullmatch(r"\(([0-9A-Fa-fx]{4}),([0-9A-Fa-fx]{4})\)", tag)
            if not m or not keyword:
                continue
            raw = (m.group(1) + m.group(2)).upper()
            mask = int("".join("0" if c == "X" else "F" for c in raw), 16)
            value = int(raw.replace("X", "0"), 16)
            vr = vr.split(" or ")[0].strip()[:2] if vr else "UN"
            if not re.fullmatch(r"[A-Z]{2}", vr):
                vr = "UN"
            out[(value, mask)] = (keyword, vr)
    exact = sorted((v, k, r) for (v, m), (k, r) in out.items() if m == 0xFFFFFFFF)
    masked = sorted((v, m, k, r) for (v, m), (k, r) in out.items() if m != 0xFFFFFFFF)
    print("//! The DICOM data dictionary: tag, keyword and value representation of every element")
    print(f"//! registered in {edition or 'DICOM PS3.6'} (NEMA, tables 6-1, 7-1 and 8-1).")
    print("//! Generated by `scripts/gen_dicom_dictionary.py`; do not edit.")
    print()
    print("/// `(tag, keyword, VR)` sorted by tag.")
    print("pub(crate) static ELEMENTS: &[(u32, &str, &str)] = &[")
    for v, k, r in exact:
        print(f'    (0x{v:08X}, "{k}", "{r}"),')
    print("];")
    print()
    print("/// Repeating-group elements: `(value, mask, keyword, VR)`; a tag matches when `tag & mask == value`.")
    print("pub(crate) static MASKED: &[(u32, u32, &str, &str)] = &[")
    for v, m, k, r in masked:
        print(f'    (0x{v:08X}, 0x{m:08X}, "{k}", "{r}"),')
    print("];")


if __name__ == "__main__":
    main()
